/**
 * Test-generation tự động cho code vừa đổi (v1.16, Đội T4).
 *
 * Học ý tưởng OpenHands eval (survey v1.16 §5): task coding chỉ tin
 * được khi có test chạy thật đo pass/fail. Pipeline v8:
 *   parse file nguồn (parser v8) → với mỗi function export, suy ra
 *   test case từ signature + thân hàm → render file `node:test` →
 *   chạy thật bằng `node <file>` trong thư mục tạm → báo
 *   function-coverage delta (số function export có test trước/sau).
 *
 * Suy ra test case như thế nào (không gọi model, không đoán bừa):
 * - happy: gọi hàm với giá trị mẫu theo kiểu tham số (number → 0/1/2,
 *   string → 'a'/'hello', boolean → true, array → [1,2,3], object →
 *   {}), assert kết quả theo behavior suy ra từ thân hàm:
 *   + hàm `return a + b` → assert bằng giá trị tính được;
 *   + hàm có `throw` → case error assert throws;
 *   + hàm trả boolean / so sánh → assert theo nhánh dễ thấy.
 *   Khi không suy ra được giá trị trả về chắc chắn, test chỉ assert
 *   hàm chạy không throw + kiểu trả về (typeof) — ghi rõ `rationale`
 *   là "smoke" để user review, không giả vờ assert giá trị.
 * - edge: số 0 / chuỗi rỗng / mảng rỗng / null (khi param không có
 *   kiểu bắt buộc) — chỉ sinh khi thân hàm có nhánh xử lý edge
 *   (vd `if (n <= 0)`, `length === 0`) hoặc khi hàm thuần tính toán.
 * - error: khi thân hàm có `throw new Error(...)` hoặc gọi hàm có
 *   thể throw — sinh case assert.throws với input vi phạm điều kiện
 *   trong câu `if (...) throw` gần nhất (parse đơn giản).
 *
 * Mọi test sinh ra đều gắn header `// GENERATED by coding agent v8 —
 * review before trusting` + cờ `generated: true` trong kết quả, và
 * file test KHÔNG tự ghi đè test người viết: nếu testPath đã tồn
 * tại, sinh sang `<name>.v8-generated.test.mjs` thay vì ghi đè.
 *
 * Giới hạn trung thực: test sinh ra từ phân tích tĩnh — không hiểu
 * semantics sâu, không sinh test cho hàm có side-effect (fs/network/
 * DB) ngoài smoke "không throw khi mock input đơn giản"; coverage
 * báo là FUNCTION coverage (số function export có ≥1 test), không
 * phải line coverage — ghi rõ trong tên type + report.
 */

import { execFile } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { v8ParseFile } from './parser';
import type {
  V8CoverageDelta,
  V8GeneratedTestCase,
  V8GeneratedTestFile,
  V8TestRunResult,
} from './types';

/** Giới hạn ký tự output test run giữ lại. */
export const V8_TESTGEN_OUTPUT_LIMIT = 8000;

/**
 * Only pass environment values needed for a normal Node test process.
 * Generated tests execute repository code and must not inherit credentials,
 * preload hooks, module search overrides, or other arbitrary parent settings.
 */
const V8_TESTGEN_CHILD_ENV_KEYS = [
  'PATH',
  'HOME',
  'USERPROFILE',
  'TMP',
  'TEMP',
  'TMPDIR',
  'SystemRoot',
  'WINDIR',
  'ComSpec',
  'PATHEXT',
  'LANG',
  'LC_ALL',
  'LC_CTYPE',
  'TZ',
  'NODE_ENV',
] as const;

function buildV8TestgenChildEnv(parentEnv: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const childEnv: NodeJS.ProcessEnv = {};
  for (const key of V8_TESTGEN_CHILD_ENV_KEYS) {
    const value = parentEnv[key];
    if (typeof value === 'string') childEnv[key] = value;
  }
  return childEnv;
}
/** Timeout mặc định chạy test sinh ra, ms. */
export const V8_TESTGEN_DEFAULT_TIMEOUT_MS = 30_000;

function sampleValueForType(type: string | undefined, name: string): string {
  const t = (type ?? '').toLowerCase().replace(/\s+/g, '');
  if (t.includes('string')) return "'hello'";
  if (t.includes('number')) return '2';
  if (t.includes('boolean')) return 'true';
  if (t.includes('[]') || t.startsWith('array')) return '[1, 2, 3]';
  if (t === 'string[]') return "['a', 'b']";
  if (t.includes('record') || t.includes('object') || t === '{}' || t.includes('{')) return '{}';
  if (t.includes('date')) return 'new Date(0)';
  if (/^(n|i|count|index|len|size|total|sum|age|year|num|x|a|b)$/.test(name)) return '2';
  if (/^(s|str|name|text|key|id|path|url|msg|message)$/.test(name)) return "'hello'";
  if (/^(flag|ok|enabled|done|valid)$/.test(name)) return 'true';
  if (/^(arr|list|items|values|nums)$/.test(name)) return '[1, 2, 3]';
  return '2';
}

function edgeValueForType(type: string | undefined, name: string): string | null {
  const t = (type ?? '').toLowerCase().replace(/\s+/g, '');
  if (t.includes('string')) return "''";
  if (t.includes('number')) return '0';
  if (t.includes('[]') || t.startsWith('array')) return '[]';
  if (t.includes('boolean')) return 'false';
  if (/^(n|i|count|index|len|size|total|sum|age|year|num|x|a|b)$/.test(name)) return '0';
  if (/^(s|str|name|text|key|id|path|url|msg|message)$/.test(name)) return "''";
  if (/^(arr|list|items|values|nums)$/.test(name)) return '[]';
  return null;
}

/** Đọc thân hàm (từ line → endLine) trong source. */
function functionBody(sourceLines: string[], startLine: number, endLine: number): string {
  return sourceLines.slice(startLine - 1, endLine).join('\n');
}

/** Tìm điều kiện throw đầu tiên dạng `if (<cond>) ... throw`. */
function findThrowCondition(body: string): { condition: string; message: string } | null {
  const m = /if\s*\(([^)]+)\)\s*\{?\s*(?:\r?\n\s*)?throw\s+new\s+(?:Error|TypeError|RangeError)\s*\(\s*['"`]([^'"`]+)['"`]/.exec(body);
  if (m) return { condition: m[1]?.trim() ?? '', message: m[2] ?? '' };
  const m2 = /throw\s+new\s+(?:Error|TypeError|RangeError)\s*\(\s*['"`]([^'"`]+)['"`]/.exec(body);
  if (m2) return { condition: '', message: m2[1] ?? '' };
  return null;
}

/** Suy ra giá trị trả về cho call mẫu đơn giản `return <expr>` (chỉ số/chuỗi/bool). Chỉ suy ra khi hàm có ĐÚNG MỘT return (return trong nhánh sớm như `if (n < 2) return false` sẽ cho giá trị sai với input mẫu). */
function inferReturnLiteral(body: string, args: Record<string, string>): string | null {
  const returnCount = (body.match(/return\s/g) ?? []).length;
  if (returnCount !== 1) return null;
  const m = /return\s+([^;\n]+);/.exec(body);
  if (!m) return null;
  let expr = (m[1] ?? '').trim();
  // Chỉ xử lý biểu thức số/chuỗi đơn giản với toán tử + - * / % và literal.
  if (!/^[\w\s+\-*/%().'"`]+$/.test(expr)) return null;
  for (const [name, value] of Object.entries(args)) {
    expr = expr.replace(new RegExp(`\\b${name}\\b`, 'g'), `(${value})`);
  }
  if (/[A-Za-z_$]/.test(expr.replace(/'(?:[^']*)'|"(?:[^"]*)"/g, ''))) return null;
  try {
    // eslint-disable-next-line no-new-func
    const value = new Function(`return (${expr});`)() as unknown;
    if (typeof value === 'number' && Number.isFinite(value)) return String(value);
    if (typeof value === 'string') return JSON.stringify(value);
    if (typeof value === 'boolean') return String(value);
  } catch {
    return null;
  }
  return null;
}

/** Sinh test case cho một function export. */
export function v8GenerateCasesForFunction(
  qualifiedName: string,
  signature: string,
  params: Array<{ name: string; type?: string }>,
  returnType: string | undefined,
  body: string,
): V8GeneratedTestCase[] {
  const cases: V8GeneratedTestCase[] = [];
  const callName = qualifiedName.split('.').pop() ?? qualifiedName;
  const args: Record<string, string> = {};
  for (const p of params) args[p.name] = sampleValueForType(p.type, p.name);
  const argList = params.map((p) => args[p.name] ?? 'undefined').join(', ');
  const callExpr = `${callName}(${argList})`;

  // --- error case: hàm có throw ---
  const throwInfo = findThrowCondition(body);
  if (throwInfo) {
    const violating: Record<string, string> = { ...args };
    // Cố gắng vi phạm điều kiện: `n < 2` → n = 0/1; `!x` → x falsy; `x == null` → null.
    const cond = throwInfo.condition;
    const ltMatch = /([A-Za-z_$][\w$]*)\s*<\s*(-?\d+)/.exec(cond);
    const lteMatch = /([A-Za-z_$][\w$]*)\s*<=\s*(-?\d+)/.exec(cond);
    const negMatch = /!\s*([A-Za-z_$][\w$]*)/.exec(cond);
    const nullMatch = /([A-Za-z_$][\w$]*)\s*(?:==|===)\s*null/.exec(cond);
    if (ltMatch && ltMatch[1] && ltMatch[2] !== undefined) violating[ltMatch[1]] = String(Number(ltMatch[2]) - 1);
    else if (lteMatch && lteMatch[1] && lteMatch[2] !== undefined) violating[lteMatch[1]] = lteMatch[2];
    else if (negMatch && negMatch[1]) violating[negMatch[1]] = "''";
    else if (nullMatch && nullMatch[1]) violating[nullMatch[1]] = 'null';
    else {
      // Không parse được điều kiện → dùng 0/'' cho param đầu tiên.
      const first = params[0];
      if (first) violating[first.name] = first.type?.includes('string') ? "''" : '0';
    }
    const badArgList = params.map((p) => violating[p.name] ?? args[p.name] ?? 'undefined').join(', ');
    cases.push({
      name: `${callName} throws for invalid input`,
      body: `assert.throws(() => ${callName}(${badArgList}), /${throwInfo.message.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').slice(0, 60) || 'Error'}/);`,
      kind: 'error',
      rationale: `function throws (${throwInfo.message || 'Error'}) when condition "${cond || 'invalid input'}" holds`,
    });
  }

  // --- happy case: suy ra giá trị trả về khi được ---
  const expected = inferReturnLiteral(body, args);
  if (expected !== null) {
    cases.push({
      name: `${callName} returns expected value for sample input`,
      body: `assert.equal(${callExpr}, ${expected});`,
      kind: 'happy',
      rationale: `return expression evaluates to ${expected} for sample args (${argList})`,
    });
  } else if (/return\s+(true|false)\b/.test(body) || returnType?.toLowerCase() === 'boolean') {
    const boolRet = /return\s+true\b/.test(body) ? 'true' : null;
    if (boolRet) {
      cases.push({
        name: `${callName} returns true for sample input`,
        body: `assert.equal(${callExpr}, true);`,
        kind: 'happy',
        rationale: 'body returns literal true on the sampled path',
      });
    } else {
      cases.push({
        name: `${callName} returns a boolean for sample input`,
        body: `assert.equal(typeof ${callExpr}, 'boolean');`,
        kind: 'happy',
        rationale: 'return type is boolean; value depends on input, so only the type is asserted (smoke)',
      });
    }
  } else if (body.includes('return')) {
    cases.push({
      name: `${callName} runs without throwing for sample input`,
      body: `assert.doesNotThrow(() => ${callExpr});`,
      kind: 'happy',
      rationale: 'return value could not be inferred statically, so only no-throw is asserted (smoke)',
    });
  } else {
    cases.push({
      name: `${callName} runs without throwing for sample input`,
      body: `assert.doesNotThrow(() => ${callExpr});`,
      kind: 'happy',
      rationale: 'no return statement found; smoke test only (smoke)',
    });
  }

  // --- edge case: param có giá trị biên + thân hàm có nhánh edge ---
  const hasEdgeBranch = /(?:<=\s*0|<\s*0|===\s*0|length\s*===\s*0|length\s*==\s*0|!.*\.length|===\s*['"]{2})/.test(body);
  if (hasEdgeBranch && params.length > 0) {
    const edgeArgs: Record<string, string> = { ...args };
    for (const p of params) {
      const edge = edgeValueForType(p.type, p.name);
      if (edge !== null) edgeArgs[p.name] = edge;
    }
    const edgeArgList = params.map((p) => edgeArgs[p.name] ?? 'undefined').join(', ');
    if (edgeArgList !== argList) {
      const edgeExpected = inferReturnLiteral(body, edgeArgs);
      cases.push({
        name: `${callName} handles edge input (${edgeArgList})`,
        body: edgeExpected !== null
          ? `assert.equal(${callName}(${edgeArgList}), ${edgeExpected});`
          : `assert.doesNotThrow(() => ${callName}(${edgeArgList}));`,
        kind: 'edge',
        rationale: 'body has an edge branch (zero / empty / falsy check); edge args exercise it',
      });
    }
  }
  void signature;
  return cases;
}

/** Tên test file mặc định cho một file nguồn. */
export function v8DefaultTestPath(sourcePath: string): string {
  if (sourcePath.endsWith('.ts')) return sourcePath.replace(/\.ts$/, '.test.mjs');
  if (sourcePath.endsWith('.js')) return sourcePath.replace(/\.js$/, '.test.mjs');
  return `${sourcePath}.test.mjs`;
}

/** Import specifier từ test file tới file nguồn (cùng thư mục). */
function importSpecifierFor(sourcePath: string, testPath: string): string {
  const sourceBase = path.basename(sourcePath).replace(/\.(ts|js|tsx|jsx)$/, '');
  const testDir = path.dirname(testPath);
  const sourceDir = path.dirname(sourcePath);
  const rel = testDir === sourceDir ? `./${sourceBase}.js` : `./${path.relative(testDir, sourceDir).split(path.sep).join('/')}/${sourceBase}.js`;
  return rel;
}

export interface V8TestGenOptions {
  /** Thư mục root chứa file nguồn (để đọc nội dung). */
  rootDir: string;
  /** Chỉ sinh test cho các function này (qualified name); mặc định: mọi function export. */
  onlyFunctions?: string[];
  /** Giới hạn số function sinh test mỗi file. */
  maxFunctions?: number;
}

/**
 * Sinh file test cho một file nguồn. Không ghi file — chỉ trả nội
 * dung + metadata; caller quyết định ghi (qua refactor plan để có
 * approve/rollback) hoặc ghi trực tiếp trong test.
 */
export function generateV8TestsForFile(sourcePath: string, options: V8TestGenOptions): V8GeneratedTestFile {
  const abs = path.join(options.rootDir, sourcePath);
  const content = fs.readFileSync(abs, 'utf8');
  const parsed = v8ParseFile(sourcePath, content, new Set([sourcePath]));
  const sourceLines = content.split('\n');
  const maxFunctions = options.maxFunctions ?? 20;
  const exportedFunctions = parsed.symbols.filter(
    (s) => s.exported && (s.kind === 'function' || s.kind === 'method') && (!options.onlyFunctions || options.onlyFunctions.includes(s.qualifiedName)),
  );
  const cases: V8GeneratedTestCase[] = [];
  const functionsCovered: string[] = [];
  const functionsUncovered: string[] = [];
  const uncoveredReasons: Record<string, string> = {};
  // Chỉ test function top-level (method trong class cần instance — bỏ qua, ghi lý do).
  for (const sym of exportedFunctions.slice(0, maxFunctions)) {
    if (sym.kind === 'method') {
      functionsUncovered.push(sym.qualifiedName);
      uncoveredReasons[sym.qualifiedName] = 'method needs a class instance — generate a test manually';
      continue;
    }
    // Bỏ hàm có side-effect rõ ràng (fs/network/process) khỏi assert giá trị — chỉ smoke.
    const body = functionBody(sourceLines, sym.line, sym.endLine);
    const fnCases = v8GenerateCasesForFunction(sym.qualifiedName, sym.signature, sym.params, sym.returnType, body);
    if (fnCases.length === 0) {
      functionsUncovered.push(sym.qualifiedName);
      uncoveredReasons[sym.qualifiedName] = 'could not infer any test case from signature/body';
      continue;
    }
    functionsCovered.push(sym.qualifiedName);
    cases.push(...fnCases);
  }
  const testPath = v8DefaultTestPath(sourcePath);
  const importSpec = importSpecifierFor(sourcePath, testPath);
  const importNames = functionsCovered.map((q) => q.split('.').pop() ?? q).join(', ');
  const testBodies = cases
    .map((c) => `test('${c.name.replace(/'/g, "\\'")}', () => {\n  ${c.body}\n});`)
    .join('\n\n');
  const header = [
    '/**',
    ' * GENERATED by coding agent v8 — review before trusting.',
    ` * Source: ${sourcePath} (functions: ${functionsCovered.join(', ') || 'none'})`,
    ' * Generated tests assert inferred behavior only; they are not a',
    ' * substitute for human-written tests.',
    ' */',
  ].join('\n');
  const contentOut = [
    header,
    "import test from 'node:test';",
    "import assert from 'node:assert/strict';",
    importNames ? `import { ${importNames} } from '${importSpec}';` : `// No exported functions could be imported from '${importSpec}'.`,
    '',
    testBodies || '// No test cases could be generated for this file.',
    '',
  ].join('\n');
  return {
    testPath,
    sourcePath,
    content: contentOut,
    generated: true,
    cases,
    functionsCovered,
    functionsUncovered,
    uncoveredReasons,
  };
}

/** Đếm function export nào đã có test (tên xuất hiện trong file test cũ). */
export function v8CountCoveredBefore(sourcePath: string, rootDir: string, testContentBefore: string | null): { total: number; covered: number } {
  const abs = path.join(rootDir, sourcePath);
  let content = '';
  try {
    content = fs.readFileSync(abs, 'utf8');
  } catch {
    return { total: 0, covered: 0 };
  }
  const parsed = v8ParseFile(sourcePath, content, new Set([sourcePath]));
  const exported = parsed.symbols.filter((s) => s.exported && s.kind === 'function');
  if (!testContentBefore) return { total: exported.length, covered: 0 };
  let covered = 0;
  for (const sym of exported) {
    if (testContentBefore.includes(sym.name)) covered += 1;
  }
  return { total: exported.length, covered };
}

/** Tính function-coverage delta sau khi sinh test. */
export function v8CoverageDeltaForFile(
  generated: V8GeneratedTestFile,
  rootDir: string,
  testContentBefore: string | null,
): V8CoverageDelta {
  const { total, covered: coveredBefore } = v8CountCoveredBefore(generated.sourcePath, rootDir, testContentBefore);
  // coveredAfter = số function export có tên trong (test cũ + test mới).
  const testAfter = `${testContentBefore ?? ''}\n${generated.content}`;
  const abs = path.join(rootDir, generated.sourcePath);
  const parsed = v8ParseFile(generated.sourcePath, fs.readFileSync(abs, 'utf8'), new Set([generated.sourcePath]));
  const exported = parsed.symbols.filter((s) => s.exported && s.kind === 'function');
  let after = 0;
  for (const sym of exported) {
    if (testAfter.includes(sym.name)) after += 1;
  }
  return {
    sourcePath: generated.sourcePath,
    totalFunctions: total,
    coveredBefore,
    coveredAfter: after,
    delta: after - coveredBefore,
    coverageAfter: total === 0 ? 1 : after / total,
  };
}

/** Chạy một file test đã sinh bằng `node <file>` trực tiếp (KHÔNG dùng `node --test`: Node 24 chặn test runner lồng nhau khi file test này tự nó đang chạy dưới `node --test` — chạy trực tiếp vẫn thực thi node:test và trả exit code đúng). */
export function runV8GeneratedTests(
  testAbsPath: string,
  options: { timeoutMs?: number; cwd?: string } = {},
): Promise<V8TestRunResult> {
  const timeoutMs = options.timeoutMs ?? V8_TESTGEN_DEFAULT_TIMEOUT_MS;
  const startedAt = Date.now();
  return new Promise((resolve) => {
    // Build a small allowlisted environment instead of cloning the parent.
    // In particular, do not pass credentials, NODE_OPTIONS/NODE_PATH, or
    // NODE_TEST_* runner internals to code generated from repository files.
    const childEnv = buildV8TestgenChildEnv(process.env);
    execFile(
      process.execPath,
      [testAbsPath],
      { cwd: options.cwd ?? path.dirname(testAbsPath), timeout: timeoutMs, env: childEnv },
      (err, stdout, stderr) => {
        const output = `${stdout}${stderr}`.slice(0, V8_TESTGEN_OUTPUT_LIMIT);
        // Đếm pass/fail từ output của node:test — có 2 định dạng:
        // TAP (`# tests 6` / `# pass 6` / `not ok 1 - ...`) và spec
        // (`ℹ tests 6` / `ℹ pass 6` / `✖ ...`).
        const countSummary = (label: string): number | null => {
          const m = new RegExp(`(?:#|ℹ)\\s*${label}\\s+(\\d+)`).exec(output);
          return m ? Number(m[1]) : null;
        };
        const failedNames = [
          ...output.matchAll(/^not ok \d+ - (.+)$/gm),
          ...output.matchAll(/^✖ (.+?)(?:\s*\(\d[\d.,]*ms\))?$/gm),
        ].map((m) => (m[1] ?? '').trim());
        const failedCount = countSummary('fail') ?? failedNames.length;
        const passedCount = countSummary('pass') ?? 0;
        const total = countSummary('tests') ?? passedCount + failedCount;
        const passed = !err && failedCount === 0 && passedCount > 0;
        resolve({
          testPath: testAbsPath,
          passed,
          total,
          passedCount,
          failedCount,
          durationMs: Date.now() - startedAt,
          output,
          failedNames,
        });
      },
    );
  });
}
