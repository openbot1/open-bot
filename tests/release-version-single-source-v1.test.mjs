import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relativePath) => fs.readFileSync(path.join(repoRoot, relativePath), 'utf8');

test('the root package version drives workspace metadata and runtime version reports', () => {
  const rootVersion = JSON.parse(read('package.json')).version;
  assert.equal(typeof rootVersion, 'string');

  const check = spawnSync(process.execPath, [
    path.join(repoRoot, 'scripts/sync-version.mjs'),
    '--check',
  ], { cwd: repoRoot, encoding: 'utf8' });
  assert.equal(check.status, 0, `${check.stdout}\n${check.stderr}`);

  const generatedSource = [
    '/**',
    ' * Generated by scripts/sync-version.mjs from the root package.json.',
    ' * Do not edit this file directly.',
    ' */',
    `export const APP_VERSION = ${JSON.stringify(rootVersion)};`,
    '',
  ].join('\n');
  for (const relativePath of [
    'packages/core/src/appVersion.ts',
    'apps/desktop/src/appVersion.ts',
  ]) {
    assert.equal(read(relativePath), generatedSource, `${relativePath} must be generated from root package.json`);
  }

  const consumers = [
    ['packages/core/src/mcp/server.ts', 'MCP_SERVER_VERSION = APP_VERSION'],
    ['packages/core/src/mcp/client.ts', 'MCP_CLIENT_VERSION = APP_VERSION'],
    ['packages/core/src/a2a/server.ts', 'options.version ?? APP_VERSION'],
    ['packages/core/src/mcp/appsCatalogV112.ts', 'MCP_APPS_V112_HOST_VERSION = APP_VERSION'],
    ['packages/core/src/mcp/appsUiDialect.ts', 'hostVersion: overrides.hostVersion ?? APP_VERSION'],
    ['packages/core/src/skills/v13/localMarketplace.ts', 'OPEN_BOT_VERSION = APP_VERSION'],
    ['packages/tools/src/fleetV9Tools.ts', 'default ${APP_VERSION}'],
    ['apps/desktop/src/renderer/components/McpAppHostV13.tsx', 'hostVersion: APP_VERSION'],
  ];
  for (const [relativePath, expected] of consumers) {
    assert.ok(read(relativePath).includes(expected), `${relativePath} must consume the shared app version`);
  }
  assert.ok(read('packages/core/src/index.ts').includes("export { APP_VERSION } from './appVersion';"));
});
