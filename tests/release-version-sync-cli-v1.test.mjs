import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceScript = path.join(repoRoot, 'scripts/sync-version.mjs');
const FIXTURE_VERSION = '1.2.3';
const WORKSPACES = [
  { manifest: 'apps/cli/package.json', lock: 'apps/cli', name: '@open-bot/cli' },
  { manifest: 'apps/desktop/package.json', lock: 'apps/desktop', name: '@open-bot/desktop' },
  { manifest: 'packages/core/package.json', lock: 'packages/core', name: '@open-bot/core' },
  { manifest: 'packages/tools/package.json', lock: 'packages/tools', name: '@open-bot/tools' },
];
const GENERATED_FILES = [
  'packages/core/src/appVersion.ts',
  'apps/desktop/src/appVersion.ts',
];
const LOCK_ENTRIES = ['', ...WORKSPACES.map((workspace) => workspace.lock)];

function writeText(root, relativePath, content) {
  const filePath = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function writeJson(root, relativePath, value) {
  writeText(root, relativePath, JSON.stringify(value, null, 2) + '\n');
}

function readJson(root, relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), 'utf8'));
}

function generatedSource(version) {
  return [
    '/**',
    ' * Generated by scripts/sync-version.mjs from the root package.json.',
    ' * Do not edit this file directly.',
    ' */',
    'export const APP_VERSION = ' + JSON.stringify(version) + ';',
    '',
  ].join('\n');
}

function createFixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'open-bot-version-sync-'));
  fs.mkdirSync(path.join(root, 'scripts'), { recursive: true });
  fs.copyFileSync(sourceScript, path.join(root, 'scripts/sync-version.mjs'));

  writeJson(root, 'package.json', { name: 'open-bot', version: FIXTURE_VERSION });
  for (const workspace of WORKSPACES) {
    writeJson(root, workspace.manifest, {
      name: workspace.name,
      version: FIXTURE_VERSION,
    });
  }
  writeJson(root, 'package-lock.json', {
    name: 'open-bot',
    version: FIXTURE_VERSION,
    lockfileVersion: 3,
    requires: true,
    packages: Object.fromEntries(
      LOCK_ENTRIES.map((entry) => [
        entry,
        { name: entry ? undefined : 'open-bot', version: FIXTURE_VERSION },
      ]),
    ),
  });
  for (const relativePath of GENERATED_FILES) {
    writeText(root, relativePath, generatedSource(FIXTURE_VERSION));
  }
  return root;
}

function runSync(root, args = []) {
  return spawnSync(
    process.execPath,
    [path.join(root, 'scripts/sync-version.mjs'), ...args],
    { cwd: root, encoding: 'utf8' },
  );
}

function cleanupFixture(root) {
  fs.rmSync(root, { recursive: true, force: true });
}

test('version:check reports metadata drift without modifying any fixture file', (t) => {
  const root = createFixture();
  t.after(() => cleanupFixture(root));

  writeText(root, GENERATED_FILES[0], generatedSource('9.9.9'));
  const cliManifest = readJson(root, WORKSPACES[0].manifest);
  cliManifest.version = '9.9.9';
  writeJson(root, WORKSPACES[0].manifest, cliManifest);
  const lock = readJson(root, 'package-lock.json');
  lock.packages[WORKSPACES[2].lock].version = '9.9.9';
  writeJson(root, 'package-lock.json', lock);

  const unchangedPaths = [
    GENERATED_FILES[0],
    WORKSPACES[0].manifest,
    'package-lock.json',
  ];
  const before = new Map(
    unchangedPaths.map((relativePath) => [
      relativePath,
      fs.readFileSync(path.join(root, relativePath), 'utf8'),
    ]),
  );

  const result = runSync(root, ['--check']);
  const output = result.stdout + result.stderr;
  assert.equal(result.status, 1, output);
  assert.match(output, /Version metadata is out of sync/);
  assert.match(output, /packages\/core\/src\/appVersion\.ts/);
  assert.match(output, /apps\/cli\/package\.json/);
  assert.match(output, /package-lock\.json \(packages\/core\)/);

  for (const relativePath of unchangedPaths) {
    assert.equal(
      fs.readFileSync(path.join(root, relativePath), 'utf8'),
      before.get(relativePath),
      relativePath + ' must remain byte-for-byte unchanged in --check mode',
    );
  }
});

test('version:sync repairs runtime modules, workspace manifests and lock entries', (t) => {
  const root = createFixture();
  t.after(() => cleanupFixture(root));

  for (const relativePath of GENERATED_FILES) {
    writeText(root, relativePath, generatedSource('9.9.9'));
  }
  for (const workspace of WORKSPACES) {
    const manifest = readJson(root, workspace.manifest);
    manifest.version = '9.9.9';
    writeJson(root, workspace.manifest, manifest);
  }
  const lock = readJson(root, 'package-lock.json');
  for (const entry of LOCK_ENTRIES) {
    lock.packages[entry].version = '9.9.9';
  }
  writeJson(root, 'package-lock.json', lock);

  const sync = runSync(root);
  assert.equal(sync.status, 0, sync.stdout + sync.stderr);

  for (const relativePath of GENERATED_FILES) {
    assert.equal(
      fs.readFileSync(path.join(root, relativePath), 'utf8'),
      generatedSource(FIXTURE_VERSION),
      relativePath,
    );
  }
  for (const workspace of WORKSPACES) {
    assert.equal(readJson(root, workspace.manifest).version, FIXTURE_VERSION);
  }
  const synchronizedLock = readJson(root, 'package-lock.json');
  for (const entry of LOCK_ENTRIES) {
    assert.equal(synchronizedLock.packages[entry].version, FIXTURE_VERSION, entry || 'root lock entry');
  }

  const check = runSync(root, ['--check']);
  assert.equal(check.status, 0, check.stdout + check.stderr);
  const repeatSync = runSync(root);
  assert.equal(repeatSync.status, 0, repeatSync.stdout + repeatSync.stderr);
  assert.match(repeatSync.stdout, /already aligned/);
});

test('version commands reject an invalid root version before touching generated metadata', (t) => {
  const root = createFixture();
  t.after(() => cleanupFixture(root));

  const rootManifest = readJson(root, 'package.json');
  rootManifest.version = '1.2';
  writeJson(root, 'package.json', rootManifest);
  const generatedBefore = fs.readFileSync(path.join(root, GENERATED_FILES[0]), 'utf8');

  const result = runSync(root, ['--check']);
  assert.equal(result.status, 1, result.stdout + result.stderr);
  assert.match(result.stderr, /Root package\.json must contain a valid semver version/);
  assert.equal(
    fs.readFileSync(path.join(root, GENERATED_FILES[0]), 'utf8'),
    generatedBefore,
  );
});
